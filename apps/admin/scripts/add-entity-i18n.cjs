const deepMerge = (target, source) => {
  for (const key of Object.keys(source)) {
    if (
      source[key] &&
      typeof source[key] === 'object' &&
      !Array.isArray(source[key]) &&
      target[key] &&
      typeof target[key] === 'object' &&
      !Array.isArray(target[key])
    ) {
      deepMerge(target[key], source[key])
    } else {
      target[key] = source[key]
    }
  }
}

for (const lang of ['en', 'fa', 'ar']) {
  const filePath = path.join(localesDir, `${lang}.json`)
  const raw = fs.readFileSync(filePath, 'utf8')
  const hasBom = raw.charCodeAt(0) === 0xfeff
  const json = JSON.parse(raw.replace(/^\uFEFF/, ''))
  const extra = perLocale[lang]
  deepMerge(json.nav, extra.nav)
  deepMerge(json.page_titles, extra.page_titles)
  deepMerge(json.common, extra.common)
  for (const key of Object.keys(translations)) {
    json[key] = translations[key]
  }
  const out = JSON.stringify(json, null, 2)
  const lineEnded = out.replace(/\r\n/g, '\n')
  fs.writeFileSync(filePath, (hasBom ? '\uFEFF' : '') + lineEnded + '\n', 'utf8')
  console.log(`${lang}.json updated`)
}
